"""Generate lib_path_planning.def for the proxy from the ORIGINAL plugin's export table.

usage:
  "C:\\Program Files\\Python313\\python.exe" -I -X utf8 gen_def.py <original lib_path_planning.dll> <out.def>

Every export keeps its name and ordinal. All names except the ones in IMPLEMENTED become
PE forwarders to lib_path_planning_orig.<name>; IMPLEMENTED names are exported from proxy.c.
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from pe_exports import parse_exports  # noqa: E402

IMPLEMENTED = {'GenJs001ReliefGcodeSync'}
TARGET = 'lib_path_planning_orig'


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    src, dst = sys.argv[1], sys.argv[2]
    r = parse_exports(src)
    names = sorted(r['names'], key=lambda e: e[1])
    for name, _o, _rva, fwd in names:
        if not re.fullmatch(r'[A-Za-z_][A-Za-z0-9_]*', name):
            sys.exit('export name not usable in a .def file: %r' % name)
        if fwd:
            sys.exit('the given DLL already forwards %s (%s): is it the proxy?' % (name, fwd))
    missing = IMPLEMENTED - {n for n, _o, _r, _f in names}
    if missing:
        sys.exit('original does not export %s' % ', '.join(sorted(missing)))
    lines = [
        '; lib_path_planning.def - generated by gen_def.py, do not edit',
        '; source: %s (%d bytes)' % (os.path.basename(src), os.path.getsize(src)),
        '; %d named exports, ordinal base %d; implemented in proxy.c: %s'
        % (len(names), r['base'], ', '.join(sorted(IMPLEMENTED))),
        'LIBRARY %s' % r['dllname'],
        'EXPORTS',
    ]
    for name, ordinal, _rva, _fwd in names:
        if name in IMPLEMENTED:
            lines.append('    %s @%d' % (name, ordinal))
        else:
            lines.append('    %s = %s.%s @%d' % (name, TARGET, name, ordinal))
    text = '\r\n'.join(lines) + '\r\n'
    text.encode('ascii')
    with open(dst, 'w', encoding='ascii', newline='') as f:
        f.write(text)
    print('wrote %s: %d exports (%d forwarded, %d implemented)'
          % (dst, len(names), len(names) - len(IMPLEMENTED), len(IMPLEMENTED)))


if __name__ == '__main__':
    main()
